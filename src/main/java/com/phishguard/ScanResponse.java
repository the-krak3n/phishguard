package com.phishguard;

import com.fasterxml.jackson.annotation.JsonUnwrapped;

/**
 * What a scan endpoint returns: all fields of the (blended) {@link PhishingDetector.Result}
 * (score, classification, indicators, urls, recommendations, notes, summary) at the top level,
 * plus information about how the score was produced.
 */
public class ScanResponse {

    public static final String ENGINE_HYBRID = "HYBRID";
    public static final String ENGINE_RULES = "RULES";

    @JsonUnwrapped
    public final PhishingDetector.Result result;

    /** HYBRID (rules + Gemini) or RULES (offline fallback). */
    public final String engine;
    public final int ruleScore;
    /** Gemini's own score, or null when Gemini was not used. */
    public final Integer aiScore;
    public final String aiVerdict;
    /** Gemini model that answered, or null. */
    public final String model;
    /** Why Gemini was not used (offline mode, error ...), or null. */
    public final String aiStatus;
    /** Text Gemini read from the image (image scans). */
    public final String extractedText;
    /** Transcript that was analysed (voice scans; generated by Gemini when audio was uploaded). */
    public final String transcript;

    public ScanResponse(PhishingDetector.Result result, String engine, int ruleScore, Integer aiScore, String aiVerdict,
                        String model, String aiStatus, String extractedText, String transcript) {
        this.result = result;
        this.engine = engine;
        this.ruleScore = ruleScore;
        this.aiScore = aiScore;
        this.aiVerdict = aiVerdict;
        this.model = model;
        this.aiStatus = aiStatus;
        this.extractedText = extractedText;
        this.transcript = transcript;
    }

    /** Result produced by the rule engine alone (offline mode or Gemini error). */
    public static ScanResponse rulesOnly(PhishingDetector.Result rules, String reason, String extractedText, String transcript) {
        return new ScanResponse(rules, ENGINE_RULES, rules.score, null, null, null, reason, extractedText, transcript);
    }
}
